// Три виміри однієї довжини, м. Невідоме одне — x, рівнянь три:
//   x = 10.02,  x = 10.05,  x = 9.98
const l = [10.02, 10.05, 9.98];
const mean = l.reduce((s, v) => s + v, 0) / l.length;

for (const guess of [10.02, 10.05, 9.98, mean]) {
  // Відхилення кожного виміру від обраного значення, мм.
  const v = l.map((li) => +((guess - li) * 1000).toFixed(1));
  console.log(`x = ${guess.toFixed(4)} м → відхилення`, v, "мм");
}

