import numpy as np

# Три виміри однієї довжини, м. Невідоме одне — x, рівнянь три:
#   x = 10.02,  x = 10.05,  x = 9.98
l = np.array([10.02, 10.05, 9.98])

for guess in [10.02, 10.05, 9.98, l.mean()]:
    v = (guess - l) * 1000           # відхилення кожного виміру, мм
    print(f"x = {guess:.4f} м → відхилення {np.round(v, 1)} мм")

